const slugTitle = (slug = "") =>
  String(slug)
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");

export const getProductDetailBySlug = (slug = "iphone-14-128gb") => {
  if (!slug || slug.includes("iphone-14")) {
    return {
      ...baseProduct,
      slug,
    };
  }

  const prettyName = slugTitle(slug);

  return {
    ...baseProduct,
    slug,
    name: `${prettyName} | Chính hãng`,
    shortName: prettyName,
    sku: `${slug.toUpperCase()}-STD`,
  };
};
